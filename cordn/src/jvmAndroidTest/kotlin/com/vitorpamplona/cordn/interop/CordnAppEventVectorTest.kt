/**
 * cordn app events against cordn-web, the reference client, in both directions.
 *
 * `resources/cordn/app-events/` is generated by `cordn/tools/cordn-vector-gen/app-events.sh`,
 * which runs cordn-web's own builders and interpretation code (`references.ts`, `polls.ts`,
 * `calls.ts`, `calendar.ts`, `emoji.ts`, `chatMentions.ts`, `chatMediaCipher.ts`,
 * `chatUnreadLedger.svelte.ts`) under Node:
 *
 * - `theirs-cordn-web.json`: envelopes cordn-web's builders produce, and what cordn-web decides
 *   about each message. We must decide the same ([theirsReadByUs]).
 * - `ours-read-by-cordn-web.json`: envelopes [OurAppEvents] produces, and what cordn-web made of
 *   them. Our builders must still produce exactly those envelopes, and we must read them as
 *   cordn-web did ([oursReadByThem]).
 *
 * "Decides" is [CordnAppEventView]: row or not, reply, edit, deletion, pin, reactions (custom
 * emoji included), mentions, which row a `p` tag lights up, media, call, calendar, poll tally.
 *
 * Where cordn-web departs from the spec and we keep the spec, `divergences` names the case, the
 * fields and the reason. Each entry must still differ: one that starts agreeing fails, so it
 * gets deleted rather than left to hide a regression.
 */
class CordnAppEventVectorTest {
    private class Divergence(
        val fields: Set<String>,
        val reason: String,
    )

    private val divergences =
        mapOf(
            // calendar-events.md §6: "cancellations by other members are ignored". cordn-web keeps
            // the newest-cursor cancellation from anyone and checks its author afterwards, so Bob's
            // stray kind 5 un-cancels Alice's event there (and her cancellation's `e` then reads as
            // a plain deletion). We follow the spec; README "divergences" #6.
            "calendar: a non-author's cancellation after the author's" to
                Divergence(setOf("deleted", "calendar"), "calendar-events.md §6: a non-author's cancellation is ignored"),
            // spec/02.md §6 requires no kinds. cordn-web draws every unknown-kind message as a row,
            // every revision of an addressable one and a blank one included; CordnStreamRows keeps
            // the newest revision per NIP-01 and drops a blank row that has no `alt` to show.
            "kinds cordn-web does not draw: every addressable revision and a blank one keep their rows" to
                Divergence(setOf("row"), "CordnStreamRows: NIP-01 replacement and no blank rows for undrawn kinds"),
        )

    /**
     * What each of our cases is for, checked against cordn-web's reading of it. Agreeing with
     * cordn-web is not enough when we both drop something: a mention neither client notifies
     * agrees perfectly. (case, message position, field cordn-web must have set)
     */
    private val intents =
        listOf(
            Triple("mention: a nostr:npub in content", 0, "attention"),
            Triple("custom emoji reaction", 0, "custom_emoji"),
            Triple("reactions, and one taken back", 0, "reactions"),
            Triple("pin and unpin", 0, "pinned"),
            Triple("poll and votes", 0, "poll"),
            Triple("deletion by the author", 0, "deleted"),
        )

    @Test
    fun theirsReadByUs() = checkViews(vectors("theirs-cordn-web.json"))

    @Test
    fun oursReadByThem() {
        writeOurStreams()

        val vectors = vectors("ours-read-by-cordn-web.json")
        val recorded = vectors["cases"]!!.jsonArray.associateBy { it.jsonObject["name"]!!.jsonPrimitive.content }
        assertEquals(
            OurAppEvents.cases.map { it.name }.toSet(),
            recorded.keys,
            "OurAppEvents changed: regenerate with cordn/tools/cordn-vector-gen/app-events.sh",
        )
        OurAppEvents.cases.forEach { case ->
            val events =
                recorded
                    .getValue(case.name)
                    .jsonObject["stream"]!!
                    .jsonArray
                    .map { it.jsonObject["event"]!! }
            assertEquals(
                events,
                case.stream.map { it.envelope.toJsonObject() },
                "${case.name}: our builders no longer produce what cordn-web read; regenerate with app-events.sh and check its new reading",
            )
        }

        val missed =
            intents.mapNotNull { (name, position, field) ->
                val case = recorded.getValue(name).jsonObject
                val id =
                    case["stream"]!!
                        .jsonArray[position]
                        .jsonObject["event"]!!
                        .jsonObject["id"]!!
                        .jsonPrimitive.content
                if (case["expect"]!!.jsonObject[id]!!.jsonObject[field] == null) "[$name] cordn-web did not see `$field` on message ${position + 1}" else null
            } +
                listOfNotNull(
                    // The voice note's bars: cordn-web reads comma-separated 0-1 peaks.
                    recorded.getValue("media: an image and a voice note").jsonObject.let { case ->
                        val id =
                            case["stream"]!!
                                .jsonArray[1]
                                .jsonObject["event"]!!
                                .jsonObject["id"]!!
                                .jsonPrimitive.content
                        val media = case["expect"]!!.jsonObject[id]!!.jsonObject["media"]!!.jsonObject
                        if (media["waveform"] == null) "[media] cordn-web read no waveform from our voice note" else null
                    },
                )
        if (missed.isNotEmpty()) fail(missed.joinToString("\n"))

        checkViews(vectors)
    }

    private fun checkViews(vectors: JsonObject) {
        val problems = mutableListOf<String>()
        vectors["cases"]!!.jsonArray.forEach { element ->
            val case = element.jsonObject
            val name = case["name"]!!.jsonPrimitive.content
            val viewer = case["me"]!!.jsonPrimitive.content
            val now = case["now"]!!.jsonPrimitive.long
            val stream =
                case["stream"]!!.jsonArray.map {
                    val delivered = it.jsonObject
                    // fromJsonObject recomputes the NIP-01 id: their ids must be ours too.
                    CordnDeliveredMessage(CordnEnvelope.fromJsonObject(delivered["event"]!!.jsonObject), delivered["cursor"]!!.jsonPrimitive.long)
                }
            val expected = case["expect"]!!.jsonObject
            val actual = CordnAppEventView.of(stream, viewer, now)
            val divergence = divergences[name]
            var diverged = false

            stream.forEachIndexed { position, message ->
                val want = CordnAppEventView.canonical(expected[message.envelope.id]!!).jsonObject
                val got = CordnAppEventView.canonical(actual.getValue(message.envelope.id)).jsonObject
                (want.keys + got.keys).forEach { field ->
                    if (want[field] == got[field]) return@forEach
                    if (divergence != null && field in divergence.fields) {
                        diverged = true
                    } else {
                        problems += "[$name] message ${position + 1} (kind ${message.envelope.kind}) `$field`: cordn-web ${want[field]}, cordn-kmp ${got[field]}"
                    }
                }
            }
            if (divergence != null && !diverged) problems += "[$name] documented divergence no longer differs (${divergence.reason}): delete its entry"
        }
        if (problems.isNotEmpty()) fail(problems.joinToString("\n"))
    }

    private fun vectors(name: String): JsonObject =
        Json
            .parseToJsonElement(
                checkNotNull(CordnAppEventVectorTest::class.java.getResourceAsStream("/cordn/app-events/$name")) {
                    "missing $name: run cordn/tools/cordn-vector-gen/app-events.sh"
                }.use { it.readBytes() }.decodeToString(),
            ).jsonObject

    /** The input `app-events.mjs` reads for the OURS → THEM half. Cheap, so written on every run. */
    private fun writeOurStreams() {
        val out = File(System.getProperty("cordn.interop.out") ?: "build/interop", "app-events").also { it.mkdirs() }
        val json =
            buildJsonObject {
                put("producer", OurAppEvents.PRODUCER)
                putJsonArray("cases") {
                    OurAppEvents.cases.forEach { case ->
                        addJsonObject {
                            put("name", case.name)
                            put("source", OurAppEvents.PRODUCER)
                            put("me", case.viewer)
                            put("now", OurAppEvents.NOW)
                            putJsonArray("stream") {
                                case.stream.forEach { message ->
                                    addJsonObject {
                                        put("cursor", message.cursor)
                                        put("at", case.at.getValue(message.cursor))
                                        put("event", message.envelope.toJsonObject())
                                    }
                                }
                            }
                        }
                    }
                }
            }
        File(out, "ours-streams.json").writeText(Json.encodeToString(JsonObject.serializer(), json))
        assertTrue(File(out, "ours-streams.json").length() > 0)
    }
}
